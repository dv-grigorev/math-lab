// Подтема «Графический метод в (x; y)»: без памятки — разборы и тренировочные задачи.
(function () {
  const S = PL.sets;
  const pick = (rng, arr) => arr[Math.floor(rng() * arr.length)];
  const int = (rng, lo, hi) => lo + Math.floor(rng() * (hi - lo + 1));
  // множитель (x − r): «(x - 2)», «(x + 1)», «x»
  const factor = (r) => (r === 0 ? "x" : `(x ${r > 0 ? "-" : "+"} ${Math.abs(r)})`);
  const num = (v) => S.num(S.surd(v));
  const ASK = { "=0": "не имеет решений", "=1": "имеет ровно одно решение", "=2": "имеет ровно два решения",
    "=3": "имеет ровно три решения", "=4": "имеет ровно четыре решения", "=8": "имеет ровно восемь решений" };
  const ROOTS = { "=2": "ровно два корня", "=3": "ровно три корня", "=4": "ровно четыре корня" };

  PL.topics.push({
    id: "graph-xy",
    title: "Графический метод в (x; y)",
    view: { x: [-6, 6], y: [-6, 6] },
    memo: [],

    // ---------- Разборы ----------
    examples: [
      {
        title: "Ромб и окружность",
        text: "При каких значениях параметра $a$ система имеет ровно четыре решения?",
        system: ["|x| + |y| = 2", "x^2 + y^2 = a^2"],
        task: { eq: ["|x| + |y| = 2", "x^2 + y^2 = a^2"], ask: "=4" },
        answer: "{-2; -√2; √2; 2}",
        steps: [
          { html: "$|x| + |y| = 2$ — <b>квадрат-ромб</b> с вершинами $(±2; 0)$ и $(0; ±2)$: в каждой четверти это отрезок прямой, например $x + y = 2$ при $x, y ≥ 0$.", a: 1, highlight: 0 },
          { html: "$x^2 + y^2 = a^2$ — окружность с центром в начале координат и радиусом $|a|$. При росте $|a|$ она <b>раздувается</b>; $a$ и $-a$ дают одно и то же.", a: 1, highlight: 1 },
          { html: "Пока радиус меньше расстояния от центра до сторон, общих точек нет. Расстояние от $O$ до прямой $x + y = 2$: $2 / sqrt(2) = sqrt(2)$.", a: 1 },
          { html: "$|a| = sqrt(2)$: окружность касается всех четырёх сторон — <b>четыре</b> решения.", a: "√2" },
          { html: "$sqrt(2) < |a| < 2$: каждую сторону окружность пересекает дважды — восемь решений.", a: 1.7 },
          { html: "$|a| = 2$: окружность проходит через четыре вершины — снова <b>четыре</b>. Дальше общих точек нет. Ответ: $a ∈ {-2; -√2; √2; 2}$.", a: 2, showAnswer: true },
        ],
      },
      {
        title: "Модуль параболы и горизонтальная прямая",
        text: "При каких значениях параметра $a$ уравнение $|x^2 - 2x - 3| = a$ имеет ровно три корня?",
        task: { eq: ["y = |x^2 - 2x - 3|", "y = a"], ask: "=3", view: { x: [-4, 6], y: [-2, 8] } },
        answer: "{4}",
        steps: [
          { html: "Корни — абсциссы общих точек графиков $y = |x^2 - 2x - 3|$ и $y = a$.", a: 2, highlight: 0 },
          { html: "Строим $y = x^2 - 2x - 3 = (x - 1)^2 - 4$ и <b>отражаем вверх</b> часть под осью: между корнями $-1$ и $3$ получается «шапка» с вершиной $(1; 4)$.", a: 2, highlight: 0 },
          { html: "$y = a$ — горизонтальные прямые. При $a < 0$ корней нет, при $a = 0$ — два ($x = -1$ и $x = 3$).", a: 0 },
          { html: "При $0 < a < 4$ прямая пересекает и «шапку», и ветви — четыре корня.", a: 2 },
          { html: "При $a = 4$ прямая касается вершины шапки — <b>три</b> корня; при $a > 4$ — два. Ответ: $a = 4$.", a: 4, showAnswer: true },
        ],
      },
      {
        title: "Уголок и поворот прямой",
        text: "При каких значениях параметра $a$ уравнение $|x - 2| = a x + 1$ имеет ровно два корня?",
        task: { eq: ["y = |x - 2|", "y = a x + 1"], ask: "=2", view: { x: [-3, 7], y: [-3, 7] } },
        answer: "(-1/2; 1)",
        steps: [
          { html: "$y = |x - 2|$ — «уголок» с вершиной $(2; 0)$, стороны с наклонами $-1$ и $1$.", a: 0.3, highlight: 0 },
          { html: "$y = a x + 1$ — прямые через точку $(0; 1)$, $a$ — угловой коэффициент: прямая <b>поворачивается</b>.", a: 0.3, highlight: 1, extras: [{ type: "point", x: 0, y: 1, label: "(0; 1)", anchor: "end" }] },
          { html: "Через вершину $(2; 0)$: $0 = 2a + 1$, $a = -1/2$. Здесь общая точка одна — вершина.", a: "-1/2" },
          { html: "При $-1/2 < a < 1$ прямая пересекает обе стороны уголка — два корня.", a: 0.3 },
          { html: "При $a = 1$ прямая параллельна правой стороне $y = x - 2$ — с ней общих точек нет, корень один. При $a > 1$ тоже один.", a: 1 },
          { html: "При $a < -1/2$ правую сторону прямая не пересекает. Ответ: $a ∈ (-1/2; 1)$.", a: 0.5, showAnswer: true },
        ],
      },
    ],

    // ---------- Генераторы ----------
    generators: [
      {
        id: "abs-parabola",
        title: "Модуль параболы и прямая y = a",
        make(rng) {
          const r1 = int(rng, -4, 2), r2 = r1 + pick(rng, [2, 4, 6]);
          const h = ((r2 - r1) / 2) ** 2, xv = (r1 + r2) / 2;
          const ask = pick(rng, ["=2", "=3", "=4"]);
          // |(x − r1)(x − r2)| = |x² + bx + c|
          const b = -(r1 + r2), c = r1 * r2;
          const f = `x^2${b === 0 ? "" : b === 1 ? " + x" : b === -1 ? " - x" : (b > 0 ? " + " : " - ") + Math.abs(b) + "x"}${c === 0 ? "" : (c > 0 ? " + " : " - ") + Math.abs(c)}`;
          const H = num(h), Z = num(0);
          const set = {
            "=4": [S.iv(Z, H, false, false)],
            "=3": [S.point(H)],
            "=2": [S.point(Z), S.iv(H, S.INF, false, false)],
          }[ask];
          return {
            text: `При каких значениях параметра $a$ уравнение $|${f}| = a$ имеет ${ROOTS[ask]}?`,
            eq: [`y = |${f}|`, "y = a"], ask,
            view: { x: [r1 - 3, r2 + 3], y: [-2, h + 3] },
            answer: S.format(S.normalize(set)),
            steps: [
              { html: `Строим $y = ${f} = ${factor(r1)}${factor(r2)}$ и отражаем вверх часть под осью: между корнями $${r1}$ и $${r2}$ — «шапка» с вершиной $(${xv}; ${h})$.`, a: h / 2, highlight: 0 },
              { html: `$y = a$ — горизонтальные прямые: $a = 0$ — два корня, $0 < a < ${h}$ — четыре, $a = ${h}$ — три, $a > ${h}$ — два.`, a: h },
              { html: `Ответ: $a ∈ ${S.format(S.normalize(set))}$.`, a: ask === "=3" ? h : ask === "=4" ? h / 2 : h + 1, showAnswer: true },
            ],
          };
        },
      },
      {
        id: "rhombus-circle",
        title: "Ромб и окружность с центром в начале координат",
        make(rng) {
          const r = pick(rng, [1, 2, 3, 4]);
          const ask = pick(rng, ["=8", "=4", "=0"]);
          // x² + y² = a: касание сторон при a = r²/2, через вершины при a = r²
          const lo = S.num(S.surd(r * r, 0, 1, 2)), hi = num(r * r);
          const set = {
            "=8": [S.iv(lo, hi, false, false)],
            "=4": [S.point(lo), S.point(hi)],
            "=0": [S.iv(S.NINF, lo, false, false), S.iv(hi, S.INF, false, false)],
          }[ask];
          return {
            text: `При каких значениях параметра $a$ система ${ASK[ask]}?`,
            system: [`|x| + |y| = ${r}`, "x^2 + y^2 = a"],
            eq: [`|x| + |y| = ${r}`, "x^2 + y^2 = a"], ask,
            view: { x: [-r - 2, r + 2], y: [-r - 2, r + 2] },
            answer: S.format(S.normalize(set)),
            steps: [
              { html: `$|x| + |y| = ${r}$ — ромб с вершинами $(±${r}; 0)$, $(0; ±${r})$. $x^2 + y^2 = a$ — окружность радиуса $sqrt(a)$ (при $a > 0$).`, a: r * r * 0.75, highlight: 0 },
              { html: `Касание сторон: радиус равен расстоянию от центра до прямой $x + y = ${r}$, то есть $${r}/sqrt(2)$: $a = ${lo.s}$ — четыре точки.`, a: lo.s },
              { html: `Между касанием и вершинами — по две точки на каждой стороне, восемь. Через вершины: $a = ${r * r}$ — снова четыре. Дальше — ни одной.`, a: r * r },
              { html: `Ответ: $a ∈ ${S.format(S.normalize(set))}$.`, a: ask === "=8" ? r * r * 0.75 : ask === "=4" ? lo.s : r * r + 1, showAnswer: true },
            ],
          };
        },
      },
      {
        id: "hyperbola-lines",
        title: "Гипербола и параллельные прямые",
        make(rng) {
          const k = pick(rng, [1, 2, 3, 4, 5, 6, 8, 9]), sg = pick(rng, [1, -1]);
          const ask = pick(rng, ["=2", "=1", "=0"]);
          // y = k/x и y = −x + a (или y = −k/x и y = x + a): x² ∓ a·x + k = 0, D = a² − 4k
          const t = S.surd(0, 2, k, 1); // 2√k
          const P = { v: t.v, s: S.surdStr(t) }, N = { v: -t.v, s: S.surdStr(S.surd(0, -2, k, 1)) };
          const set = {
            "=2": [S.iv(S.NINF, N, false, false), S.iv(P, S.INF, false, false)],
            "=1": [S.point(N), S.point(P)],
            "=0": [S.iv(N, P, false, false)],
          }[ask];
          const kk = sg * k;
          const line = sg > 0 ? "y = -x + a" : "y = x + a";
          return {
            text: `При каких значениях параметра $a$ система ${ASK[ask]}?`,
            system: [`y = ${kk}/x`, line],
            eq: [`y = ${kk}/x`, line], ask,
            view: { x: [-7, 7], y: [-7, 7] },
            answer: S.format(S.normalize(set)),
            steps: [
              { html: `$y = ${kk}/x$ — гипербола, её ветви в ${sg > 0 ? "I и III" : "II и IV"} четвертях. $${line}$ — параллельные прямые.`, a: P.v + 1, highlight: 0 },
              { html: `Подставим: ${sg > 0 ? `$${k}/x = -x + a$ ⇒ $x^2 - a x + ${k} = 0$` : `$-${k}/x = x + a$ ⇒ $x^2 + a x + ${k} = 0$`}, $D = a^2 - ${4 * k}$.`, a: P.v + 1 },
              { html: `Касание при $D = 0$: $a = ±${S.surdStr(t)}$. При $|a| > ${S.surdStr(t)}$ — две общие точки, при $|a| < ${S.surdStr(t)}$ — ни одной.`, a: P.s },
              { html: `Ответ: $a ∈ ${S.format(S.normalize(set))}$.`, a: ask === "=2" ? P.v + 1 : ask === "=1" ? P.s : 0, showAnswer: true },
            ],
          };
        },
      },
    ],
  });
})();
