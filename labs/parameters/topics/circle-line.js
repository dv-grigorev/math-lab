  // многочлен от a по коэффициентам (старший первый): [2, 0, -3] → «2a^2 - 3»
  function poly(cs) {
    const deg = cs.length - 1;
    let s = "";
    cs.forEach((c, i) => {
      if (c === 0) return;
      const pw = deg - i, v = pw === 0 ? "" : pw === 1 ? "a" : "a^" + pw;
      const m = Math.abs(c) === 1 && v ? "" : Math.abs(c);
      s += (s ? (c < 0 ? " - " : " + ") : c < 0 ? "-" : "") + m + v;
    });
    return s || "0";
  }
